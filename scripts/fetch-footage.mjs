#!/usr/bin/env node
/**
 * Downloads the desk footage for the homepage's scroll section, cuts the used
 * stretch into still frames, and writes pre-sized WebP into
 * public/images/footage/ plus a module describing them.
 *
 * Why frames and not a <video>: the section plays the clip by scroll. Setting
 * video.currentTime on every scroll event only lands on keyframes and stutters,
 * worst in Safari. Drawing one still per scroll position onto a canvas is what
 * Apple's product pages do, and it is frame-exact in every browser.
 *
 * Licence: Mixkit Stock Video Free License — commercial use, no attribution
 * required (https://mixkit.co/license/#videoFree, read 2026-10-13). Mixkit asks
 * for a credit where reasonable, so /de/bildnachweis/ gives one. The licence is
 * checked on the clip's page at fetch time: if Mixkit ever moves it to the
 * Restricted licence, the fetch fails rather than shipping it.
 *
 * Needs ffmpeg on the machine that runs it (brew install ffmpeg). The output is
 * committed, so a build never needs ffmpeg or Mixkit.
 *
 * Run: node scripts/fetch-footage.mjs
 */
import { execFileSync } from 'node:child_process';
import { mkdir, mkdtemp, readdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import sharp from 'sharp';

const CLIP = {
  id: 'desk',
  mixkitId: 1814,
  page: 'https://mixkit.co/free-stock-video/business-person-working-with-devices-1814/',
  title: 'Business person working with devices',
  alt: 'Zwei Hände tippen auf einer Tastatur, von oben auf einem Holztisch.',
  /*
   * Seconds 0.5–4.5: both hands typing. A phone enters from the right after
   * that, and the clip turns into someone using it.
   */
  start: 0.5,
  duration: 4,
  fps: 20,
  /*
   * 4:3 around the keyboard and both hands, out of the 1920×1080 source. The
   * full 16:9 frame fitted into the portrait column on desktop left the hands
   * a strip across the middle; a square cut the keyboard's ends off.
   */
  crop: { w: 1440, h: 1080, x: 250, y: 0 },
};

const WIDTHS = [960, 640];
const OUT = join(process.cwd(), 'public/images/footage');

const pageHtml = await (await fetch(CLIP.page, { headers: { 'user-agent': 'Mozilla/5.0' } })).text();
if (!pageHtml.includes('Mixkit Stock Video Free License') || pageHtml.includes('Restricted License')) {
  throw new Error(`${CLIP.page} is no longer under the Mixkit Stock Video Free License`);
}

const work = await mkdtemp(join(tmpdir(), 'footage-'));
try {
  const source = join(work, 'source.mp4');
  const video = await fetch(`https://assets.mixkit.co/videos/${CLIP.mixkitId}/${CLIP.mixkitId}-1080.mp4`);
  if (!video.ok) throw new Error(`Mixkit ${video.status} for clip ${CLIP.mixkitId}`);
  await writeFile(source, Buffer.from(await video.arrayBuffer()));

  const { w, h, x, y } = CLIP.crop;
  execFileSync('ffmpeg', [
    '-v', 'error', '-ss', String(CLIP.start), '-i', source, '-t', String(CLIP.duration),
    '-vf', `fps=${CLIP.fps},crop=${w}:${h}:${x}:${y},hqdn3d=2:2:6:6`,
    join(work, 'f-%03d.png'),
  ]);

  await rm(OUT, { recursive: true, force: true });
  await mkdir(OUT, { recursive: true });

  const pngs = (await readdir(work)).filter((f) => f.startsWith('f-')).sort();
  const bytes = Object.fromEntries(WIDTHS.map((width) => [width, 0]));
  for (const [i, png] of pngs.entries()) {
    const n = String(i).padStart(3, '0');
    for (const width of WIDTHS) {
      const out = await sharp(join(work, png)).resize({ width }).webp({ quality: 70 }).toBuffer();
      await writeFile(join(OUT, `${CLIP.id}-${n}-${width}.webp`), out);
      bytes[width] += out.length;
    }
  }

  const module = `// GENERATED by scripts/fetch-footage.mjs — do not edit by hand.

export interface Footage {
  id: string;
  /** Number of frames, named ${CLIP.id}-000 … in public/images/footage/. */
  frames: number;
  widths: number[];
  /** Width over height of every frame. */
  aspect: number;
  alt: string;
  licence: string;
  licenceUrl: string;
  title: string;
  page: string;
}

export const DESK_FOOTAGE: Footage = ${JSON.stringify(
    {
      id: CLIP.id,
      frames: pngs.length,
      widths: WIDTHS,
      aspect: Number((w / h).toFixed(4)),
      alt: CLIP.alt,
      licence: 'Mixkit Stock Video Free License',
      licenceUrl: 'https://mixkit.co/license/#videoFree',
      title: CLIP.title,
      page: CLIP.page,
    },
    null,
    2
  )};

export function footageFrame(f: Footage, index: number, width: number): string {
  return \`/images/footage/\${f.id}-\${String(index).padStart(3, '0')}-\${width}.webp\`;
}
`;
  await writeFile(join(process.cwd(), 'src/lib/footage.ts'), module);
  console.log(
    `wrote ${pngs.length} frames: ` +
      WIDTHS.map((width) => `${width}w ${(bytes[width] / 1e6).toFixed(2)} MB`).join(', ')
  );
} finally {
  await rm(work, { recursive: true, force: true });
}
